#!/usr/bin/env python3
"""Generate trap-counting base classes for the D3D9 COM interfaces the shim implements.

Usage: gen_d3d9_stubs.py third_party/d3d9-headers/directx/d3d9.h > src/libs/renderer_bgfx/src/shim/d3d9_stubs.gen.hpp
Every method gets a default body that records the call in shim::trap() so an
unported entry point shows up in the log with a counter instead of crashing.
"""
import re, sys
WANT = ['IDirect3D9', 'IDirect3DDevice9', 'IDirect3DSurface9', 'IDirect3DVertexBuffer9', 'IDirect3DIndexBuffer9',
        'IDirect3DTexture9', 'IDirect3DCubeTexture9', 'IDirect3DVolumeTexture9', 'IDirect3DVolume9',
        'IDirect3DVertexDeclaration9', 'IDirect3DVertexShader9', 'IDirect3DPixelShader9', 'IDirect3DStateBlock9']
text = open(sys.argv[1]).read()
print('// Generated by tools/shadergen/gen_d3d9_stubs.py. Do not edit.\n#pragma once\n#include <atomic>\n#include <d3d9.h>\n'
      'namespace storm::shim {\nHRESULT trap(const char *method);\n')
for name in WANT:
    m = re.search(r'DECLARE_INTERFACE_\(' + name + r',\s*\w+\)\s*\{(.*?)\n\};', text, re.S)
    body = m.group(1)
    print(f'struct {name[1:]}Stub : {name}\n{{\n    virtual ~{name[1:]}Stub() = default;')
    print('    std::atomic<ULONG> refs_{1};')
    for mm in re.finditer(r'STDMETHOD(_)?\(([^)]*)\)\s*\((.*?)\)\s*PURE;', body, re.S):
        if mm.group(1):
            ret, meth = [x.strip() for x in mm.group(2).rsplit(',', 1)]
        else:
            ret, meth = 'HRESULT', mm.group(2).strip()
        params = re.sub(r'^\s*THIS_?\s*', '', ' '.join(mm.group(3).split()))
        # Drop parameter names so unused-parameter warnings stay quiet.
        if meth == 'QueryInterface':
            impl = '{ return E_NOINTERFACE; }'
        elif meth == 'AddRef':
            impl = '{ return ++refs_; }'
        elif meth == 'Release':
            impl = '{ const ULONG r = --refs_; if (r == 0) delete this; return r; }'
        elif ret == 'HRESULT':
            impl = f'{{ return trap("{name}::{meth}"); }}'
        elif ret == 'void':
            impl = f'{{ trap("{name}::{meth}"); }}'
        else:
            impl = f'{{ trap("{name}::{meth}"); return {{}}; }}'
        print(f'    {ret} {meth}({params}) override {impl}')
    print('};\n')
print('} // namespace storm::shim')
